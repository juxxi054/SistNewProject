package spring.mvc.dto;

public class SangpumDto {

	
	private String sanmgpum;
	private int su;
	private int price;
	private String color;
	
	public String getSanmgpum() {
		return sanmgpum;
	}
	public void setSanmgpum(String sanmgpum) {
		this.sanmgpum = sanmgpum;
	}
	public int getSu() {
		return su;
	}
	public void setSu(int su) {
		this.su = su;
	}
	public int getPrice() {
		return price;
	}
	public void setPrice(int price) {
		this.price = price;
	}
	public String getColor() {
		return color;
	}
	public void setColor(String color) {
		this.color = color;
	}
	
	
}
